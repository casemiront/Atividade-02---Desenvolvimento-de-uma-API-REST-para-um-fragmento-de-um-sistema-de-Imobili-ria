CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cliente VARCHAR(255) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    telefone VARCHAR(12) NOT NULL,
    email VARCHAR(100) NOT NULL,
    dt_nascimento DATE NOT NULL
);
CREATE TABLE imoveis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_imovel VARCHAR(50) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    cep VARCHAR(10) NOT NULL,
    dormitorios INT NOT NULL CHECK (dormitorios >= 0),
    banheiros INT NOT NULL CHECK (banheiros >= 0),
    suites INT NOT NULL CHECK (suites >= 0),
    metragem INT NOT NULL CHECK (metragem > 0),
    valor_aluguel_sug DECIMAL(12,2) NOT NULL CHECK (valor_aluguel_sug > 0),
    obs TEXT
);
CREATE TABLE locacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_imovel BIGINT NOT NULL,
    id_inquilino BIGINT NOT NULL,
    ativo BOOLEAN NOT NULL,
    data_fim DATE NOT NULL,
    data_inicio DATE NOT NULL,
    dia_vencimento INT NOT NULL CHECK (dia_vencimento BETWEEN 1 AND 31),
    perc_multa DECIMAL(5,2) NOT NULL CHECK (perc_multa BETWEEN 0 AND 100),
    valor_aluguel DECIMAL(12,2) NOT NULL CHECK (valor_aluguel > 0),
    obs TEXT,
    CONSTRAINT fk_locacao_imovel FOREIGN KEY (id_imovel) REFERENCES imoveis(id),
    CONSTRAINT fk_locacao_inquilino FOREIGN KEY (id_inquilino) REFERENCES clientes(id),
    CONSTRAINT ck_datas CHECK (data_fim >= data_inicio)
);
CREATE INDEX idx_locacao_imovel ON locacao(id_imovel);
CREATE INDEX idx_locacao_inquilino ON locacao(id_inquilino);
